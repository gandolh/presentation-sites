// Generates the Open Graph card, the one image this site ships.
//
// It is the hero's drawing: the movement from the part table, drawn by the same builder the page uses
// (src/movement/svg/movement.ts) and coloured by the page's own stylesheet, on paper, with the wordmark and the
// hero's line. Nothing here is a photograph.
//
// Social platforms refuse an SVG og:image, so the drawing is wrapped in scripts/og-card.html with the real
// self-hosted Newsreader and IBM Plex Mono faces, screenshotted by headless Chrome at 1200x630, and palette-encoded
// to public/images/og-image.png, well under the 300 KB WhatsApp accepts.
//
//   npm run tavi:og            (CHROME=/path/to/chrome to pick the binary)

import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";
import { movementSvg } from "../src/movement/svg/movement.ts";

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const siteDir = join(scriptsDir, "..");
const outDir = join(siteDir, "public", "images");

const W = 1200,
  H = 630;

// The card cannot read the stylesheet's variables through Tailwind, so it takes the colour tokens and the drawing's
// rules from src/styles/global.css itself: a change to a part colour reaches the card on its next run.
const css = await readFile(join(siteDir, "src", "styles", "global.css"), "utf8");
const tokens = [...css.matchAll(/^\s*(--color-[a-z0-9-]+:[^;]+;)/gm)].map((m) => m[1]).join("\n");
const drawingAt = css.indexOf("The drawing: the movement from the part table");
if (drawingAt < 0) throw new Error("global.css lost the drawing's section");
const drawing = css.slice(css.lastIndexOf("/* ====", drawingAt));

const svg = movementSvg({
  pose: "hero",
  id: "card-movement",
  viewBox: "-250 -215 500 430",
  label: "A wristwatch movement seen from the back",
});

const FONTS = "../../../node_modules/@fontsource-variable/newsreader/files";
const MONO = "../../../node_modules/@fontsource/ibm-plex-mono/files";
const face = (family, file, style, format, weight) =>
  `@font-face{font-family:"${family}";src:url("${file}") format("${format}");font-style:${style};font-weight:${weight}}`;

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<!--
  GENERATED by scripts/gen-og.mjs: edit the generator, not this file.
  SOURCE for public/images/og-image.png. To regenerate: npm run tavi:og
-->
<style>
${face("Newsreader Variable", `${FONTS}/newsreader-latin-opsz-normal.woff2`, "normal", "woff2-variations", "200 800")}
${face("Newsreader Variable", `${FONTS}/newsreader-latin-opsz-italic.woff2`, "italic", "woff2-variations", "200 800")}
${face("IBM Plex Mono", `${MONO}/ibm-plex-mono-latin-400-normal.woff2`, "normal", "woff2", 400)}
:root{
${tokens}
}
${drawing}
*{margin:0;padding:0;box-sizing:border-box}
html,body{width:${W}px;height:${H}px;overflow:hidden}
body{position:relative;background:var(--color-paper);color:var(--color-ink);font-family:"Newsreader Variable",Georgia,serif}
.word{position:absolute;left:72px;top:64px;font-size:30px;font-style:italic;color:var(--color-ink)}
.head{position:absolute;left:72px;top:216px;font-size:88px;line-height:1;font-weight:400;letter-spacing:-0.025em;font-variation-settings:"opsz" 72}
.lede{position:absolute;left:72px;top:446px;width:440px;font-size:26px;line-height:1.4;color:var(--color-ink-2)}
.rate{position:absolute;left:72px;bottom:56px;font-family:"IBM Plex Mono",monospace;font-size:20px;color:var(--color-muted)}
.rate b{font-weight:400;color:var(--color-ink)}
.rule{position:absolute;left:72px;top:122px;width:64px;height:2px;background:var(--color-accent)}
.fig{position:absolute;left:610px;top:40px;width:550px;height:550px}
.fig svg{display:block;width:100%;height:100%}
</style></head><body>
<div class="word">Tavi Ceasornicaru</div>
<div class="rule"></div>
<h1 class="head">Six beats<br>every second</h1>
<p class="lede">A wristwatch movement you can wind, slow down and take apart.</p>
<p class="rate"><b>21,600</b> beats an hour</p>
<div class="fig">${svg}</div>
</body></html>
`;

const cardPath = join(scriptsDir, "og-card.html");
await writeFile(cardPath, html);
console.log("wrote scripts/og-card.html");

const tmp = await mkdtemp(join(tmpdir(), "tavi-og-"));
try {
  const shot = join(tmp, "card.png");
  execFileSync(
    process.env.CHROME ?? "google-chrome",
    [
      "--headless=new",
      "--disable-gpu",
      "--hide-scrollbars",
      "--force-device-scale-factor=1",
      `--window-size=${W},${H}`,
      // give the @font-face files time to load before the capture
      "--virtual-time-budget=3000",
      `--screenshot=${shot}`,
      pathToFileURL(cardPath).href,
    ],
    { stdio: "ignore" },
  );
  const info = await sharp(shot).png({ palette: true, compressionLevel: 9 }).toFile(join(outDir, "og-image.png"));
  if (info.width !== W || info.height !== H) {
    throw new Error(`og-image.png came out ${info.width}x${info.height}, expected ${W}x${H}`);
  }
  if (info.size > 300 * 1024) throw new Error(`og-image.png is ${Math.round(info.size / 1024)} KB, over 300 KB`);
  console.log(`wrote public/images/og-image.png (${Math.round(info.size / 1024)} KB)`);
} finally {
  await rm(tmp, { recursive: true, force: true });
}
